export type AdminMessageKey = keyof typeof en;
export type TParams = Record<string, string | number>;

export function t(key: AdminMessageKey, params?: TParams): string {
  const template: string = en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match));
}

/** For enum-like values whose key is built at runtime (statuses, tiers…). */
export function tMaybe(key: string, fallback?: string): string {
  return key in en ? en[key as AdminMessageKey] : (fallback ?? key.split('.').pop() ?? key);
}
